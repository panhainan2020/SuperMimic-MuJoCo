#!/usr/bin/env python3
"""Build the trained G1 variant from pinned MJLab and Unitree source assets.

This offline generator reads only the two bundled sources and mesh directory.
It never reads an older generated model or downloads any assets. MuJoCo's
3.8.1 XML writer provides the fixed inertia diagonalization/serialization.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

import mujoco


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "supermimic" / "assets" / "robots"
SOURCES = {
    "mjlab_g1_1.4.0.xml": "febdcbeffbbf84051556ae41a5ac1b43fb479a5d76bdb3f54824dbc2721c20aa",
    "unitree_g1_29dof_mode_15.urdf": "80fc328761b0d0a502d675106c234eceabb70fa09c9f7d5cbcb40c2955629bac",
}


def read_source(name: str) -> ET.Element:
    content = (ASSETS / "sources" / name).read_bytes()
    if hashlib.sha256(content).hexdigest() != SOURCES[name]:
        raise ValueError(f"Pinned source checksum mismatch: {name}")
    return ET.fromstring(content)


def required(root: ET.Element, path: str) -> ET.Element:
    value = root.find(path)
    if value is None:
        raise ValueError(f"Required source element is missing: {path}")
    return value


def generate() -> bytes:
    if mujoco.__version__ != "3.8.1":
        raise RuntimeError("Rebuilding this asset requires MuJoCo 3.8.1")
    robot = read_source("mjlab_g1_1.4.0.xml")
    unitree = read_source("unitree_g1_29dof_mode_15.urdf")
    required(robot, "compiler").set("meshdir", "meshes")

    # Diagonalize only the two selected Unitree inertias. No other mode-15
    # kinematics, meshes or collision representation enter the generated model.
    inertia_model = ET.Element("mujoco")
    world = ET.SubElement(inertia_model, "worldbody")
    for side in ("left", "right"):
        name = f"{side}_wrist_pitch_link"
        inertial = required(unitree, f"link[@name='{name}']/inertial")
        origin = required(inertial, "origin")
        if origin.get("rpy", "0 0 0") != "0 0 0":
            raise ValueError(f"Unexpected rotated source inertia: {name}")
        inertia = required(inertial, "inertia")
        body = ET.SubElement(world, "body", name=name)
        ET.SubElement(
            body, "inertial", pos=origin.attrib["xyz"],
            mass=required(inertial, "mass").attrib["value"],
            fullinertia=" ".join(inertia.attrib[k] for k in
                                 ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")),
        )
    inertia_spec = mujoco.MjSpec.from_string(ET.tostring(inertia_model, encoding="unicode"))
    inertia_spec.compile()
    diagonalized = ET.fromstring(inertia_spec.to_xml())

    for side in ("left", "right"):
        for axis in ("roll", "pitch", "yaw"):
            name = f"{side}_wrist_{axis}_link"
            source_mesh = required(unitree, f"link[@name='{name}']/visual/geometry/mesh")
            required(robot, f"asset/mesh[@name='{name}']").set(
                "file", Path(source_mesh.attrib["filename"]).name,
            )
        name = f"{side}_wrist_pitch_link"
        required(robot, f".//body[@name='{name}']/inertial").attrib = dict(
            required(diagonalized, f".//body[@name='{name}']/inertial").attrib,
        )
        yaw_origin = required(unitree, f"joint[@name='{side}_wrist_yaw_joint']/origin")
        required(robot, f".//body[@name='{side}_wrist_yaw_link']").set(
            "pos", yaw_origin.attrib["xyz"],
        )

    # Keep the trained scene's lighting and sensor contract. Actuators are
    # generated from the model's joint order; scene construction configures PD.
    required(robot, "worldbody/body/light").set("castshadow", "true")
    sensor = required(robot, "sensor")
    sensor.remove(required(sensor, "framezaxis[@name='imu_upvector']"))
    actuator = ET.SubElement(robot, "actuator")
    joints = robot.findall(".//joint")
    if len(joints) != 29:
        raise ValueError(f"Expected 29 actuated joints, got {len(joints)}")
    for joint in joints:
        ET.SubElement(actuator, "motor", name=joint.attrib["name"], joint=joint.attrib["name"])

    robot.insert(0, ET.Comment(
        " Generated by tools/build_default_robot.py from pinned MJLab 1.4.0 and Unitree sources.\n"
        "       Copyright 2025 The mjlab Developers; Copyright 2016-2022 Unitree Robotics.\n"
        "       SPDX-License-Identifier: Apache-2.0 AND BSD-3-Clause\n"
        "       Modifications: 5010 wrist assets/inertias/offsets, motors, sensor and lighting settings.\n"
        "       See ASSETS.md and sources/README.md for provenance. "
    ))
    ET.indent(robot, space="  ")
    return (ET.tostring(robot, encoding="unicode") + "\n").encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the bundled model without writing")
    args = parser.parse_args()
    result = generate()
    output = ASSETS / "g1_29dof.xml"
    if args.check:
        if output.read_bytes() != result:
            raise SystemExit("Bundled default model differs from the reproducible build")
    else:
        output.write_bytes(result)
    print(f"{'Verified' if args.check else 'Generated'} {output.relative_to(ROOT)}")
    print(f"SHA-256: {hashlib.sha256(result).hexdigest()}")


if __name__ == "__main__":
    main()
